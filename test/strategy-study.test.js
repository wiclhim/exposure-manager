const assert=require('node:assert/strict');
const {signals,study,simulate}=require('../strategy-study-engine');
const policy=require('../risk-policy');
const index=Array.from({length:1500},(_,i)=>{const close=150+i*.08+25*Math.sin(i/70);return {date:new Date(Date.UTC(2021,0,i+1)).toISOString().slice(0,10),close,high:close+2,low:close-2};});
const rows=signals(index),prefix=signals(index.slice(0,1000));
assert.deepEqual(prefix.at(-1),rows[999],'future candles cannot change an earlier signal');
assert(rows.every(r=>r.targets.recovery<=1&&r.targets.recovery>=.5),'no recovery above baseline');
assert(rows.every(r=>!r.repair||(r.close>r.ma20&&r.k>r.d)),'repair requires trend confirmation');
const result=study(index,index,index);
assert(result.train.every(r=>r.to<result.splitDate));assert(result.test.every(r=>r.from===result.splitDate));
assert(result.train.every(r=>Math.abs(r.curve[0].value-result.train[0].curve[0].value)<1e-12),'identical initial holdings and costs');
assert(result.test.every(r=>r.monthCount>0&&r.positiveMonthRate>=0&&r.positiveMonthRate<=1));
const aligned=rows.map(r=>({...r,core:r.close,lever:r.close}));
const usual=simulate(aligned,'constant',300,1400),expensive=simulate(aligned,'constant',300,1400,1.3,2);
assert(expensive.totalReturn<=usual.totalReturn,'higher costs cannot improve the same fixed strategy');
const unchanged=simulate(aligned,'trend',300,301);
const changed=structuredClone(aligned);changed[300].targets.trend=0;
assert.equal(simulate(changed,'trend',300,301).totalReturn,unchanged.totalReturn,'today signal cannot affect today return');
const r=policy.recommendation(rows,1.3,1.6);assert(Math.abs(r.next-1.6)<=.1000001);
console.log('PASS: prefix invariance, holdout boundary, fair initialization, confirmed recovery, transaction costs, signal lag and Beta cap');
